// ─── HELPER FUNCTIONS ─────────────────────────────────────────
export function getAllPerfumeProducts(): PerfumeProduct[] {
  return perfumeCategories.flatMap(cat => cat.products);
}

export function getPerfumeCategoryById(id: string): PerfumeCategory | undefined {
  return perfumeCategories.find(cat => cat.id === id);
}

export function getPerfumeProductById(id: string): PerfumeProduct | undefined {
  return getAllPerfumeProducts().find(p => p.id === id);
}

export function formatPriceMad(price: number): string {
  return new Intl.NumberFormat('fr-MA', { 
    style: 'currency', 
    currency: 'MAD',
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(price);
}
